#!/usr/bin/env python3
"""Regenerate packages/releases.toml with pinned versions and SHA-256 digests.

Maintainer tool, run when you want to bump a tool:
    scripts/pin-releases.py [NAME ...]       default: every tool in SPECS

For each tool it asks the GitHub API for the latest release, downloads the Linux archives listed in
SPECS, hashes them and writes the digests, so the installer can verify later downloads against
values reviewed in a commit instead of values fetched at install time.
Standard library only, Python 3.11 or newer.
"""

from __future__ import annotations

import hashlib
import json
import sys
import urllib.request
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "packages" / "releases.toml"

# {v} is the version without a leading "v". members are the executables to install from the archive.
SPECS = {
    "chezmoi": {
        "repo": "twpayne/chezmoi",
        "members": ["chezmoi"],
        "assets": {
            "linux-x86_64": "chezmoi_{v}_linux_amd64.tar.gz",
            "linux-aarch64": "chezmoi_{v}_linux_arm64.tar.gz",
        },
    },
    "uv": {
        "repo": "astral-sh/uv",
        "members": ["uv", "uvx"],
        "assets": {
            "linux-x86_64": "uv-x86_64-unknown-linux-gnu.tar.gz",
            "linux-aarch64": "uv-aarch64-unknown-linux-gnu.tar.gz",
        },
    },
    "lazygit": {
        "repo": "jesseduffield/lazygit",
        "members": ["lazygit"],
        "assets": {
            "linux-x86_64": "lazygit_{v}_Linux_x86_64.tar.gz",
            "linux-aarch64": "lazygit_{v}_Linux_arm64.tar.gz",
        },
    },
    "delta": {
        "repo": "dandavison/delta",
        "members": ["delta"],
        "assets": {
            "linux-x86_64": "delta-{v}-x86_64-unknown-linux-gnu.tar.gz",
            "linux-aarch64": "delta-{v}-aarch64-unknown-linux-gnu.tar.gz",
        },
    },
    "starship": {
        "repo": "starship/starship",
        "members": ["starship"],
        "assets": {
            "linux-x86_64": "starship-x86_64-unknown-linux-gnu.tar.gz",
            "linux-aarch64": "starship-aarch64-unknown-linux-musl.tar.gz",
        },
    },
    "glow": {
        "repo": "charmbracelet/glow",
        "members": ["glow"],
        "assets": {
            "linux-x86_64": "glow_{v}_Linux_x86_64.tar.gz",
            "linux-aarch64": "glow_{v}_Linux_arm64.tar.gz",
        },
    },
    "yazi": {
        "repo": "sxyazi/yazi",
        "members": ["yazi", "ya"],
        "assets": {
            "linux-x86_64": "yazi-x86_64-unknown-linux-gnu.zip",
            "linux-aarch64": "yazi-aarch64-unknown-linux-gnu.zip",
        },
    },
}


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=120) as response:  # noqa: S310 - https only
        return response.read()


def main() -> int:
    names = sys.argv[1:] or list(SPECS)
    lines = [
        "# Pinned release archives, generated by scripts/pin-releases.py, do not edit by hand.",
        "# The installer refuses any archive whose SHA-256 differs from the value here.",
        "",
    ]
    for name in names:
        spec = SPECS[name]
        tag = json.loads(fetch(f"https://api.github.com/repos/{spec['repo']}/releases/latest"))["tag_name"]
        version = tag.lstrip("v")
        lines += ["[[release]]", f'name = "{name}"', f'version = "{version}"',
                  "members = [" + ", ".join(f'"{m}"' for m in spec["members"]) + "]", ""]
        for platform, pattern in spec["assets"].items():
            asset = pattern.format(v=version)
            url = f"https://github.com/{spec['repo']}/releases/download/{tag}/{asset}"
            digest = hashlib.sha256(fetch(url)).hexdigest()
            print(f"{name} {platform} {asset} {digest}", file=sys.stderr)
            lines += [f'[release.assets."{platform}"]', f'url = "{url}"', f'sha256 = "{digest}"', ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
